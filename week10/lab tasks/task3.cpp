// Task 03(OP): Square root of a number using sqrt()
#include <iostream>
#include <cmath>
using namespace std;
 
int main()
{
    double number;
 
    cout << "Enter a number: ";
    cin >> number;
 
    cout << "The square root of " << number
         << " is: " << sqrt(number) << endl;
 
    return 0;
}
 